class Command(BaseCommand):
    help = "ایجاد داده‌های اولیه دسته‌بندی‌ها، برندها و محصولات آب پاک"

    @transaction.atomic
    def handle(self, *args, **options):
        categories = {}
        for index, data in enumerate(CATEGORIES, start=1):
            category, _ = Category.objects.update_or_create(
                slug=data["slug"],
                defaults={
                    "name": data["name"],
                    "icon": data["icon"],
                    "short_description": data["short"],
                    "description": data["description"],
                    "sort_order": data.get("order", index),
                    "is_active": True,
                },
            )
            categories[data["slug"]] = category

        brands = {}
        for data in BRANDS:
            brand, _ = Brand.objects.update_or_create(
                slug=data["slug"],
                defaults={
                    "name": data["name"],
                    "country": data["country"],
                    "description": data["description"],
                },
            )
            brands[data["slug"]] = brand

        created, updated = 0, 0
        for index, data in enumerate(PRODUCTS, start=1):
            category = categories[data["category"]]
            brand = brands[data["brand"]]
            specs = [{"label": label, "value": value} for label, value in data["specs"]]
            specs.append({"label": "برند", "value": brand.name})
            specs.append({"label": "کشور سازنده", "value": brand.country})
            specs.append({"label": "گارانتی", "value": data["warranty"]})
            specs.append({"label": "ارسال", "value": SHARED_SHIPPING})
            description = (
                f"{data['description']}\n\n"
                f"{category.description}\n\n"
                f"این محصول با ضمانت اصالت کالا از فروشگاه آب پاک عرضه می‌شود. "
                f"برای مشاوره تخصصی درباره انتخاب، نصب یا تعویض قطعات، با کارشناسان ما تماس بگیرید."
            )
            _, is_created = Product.objects.update_or_create(
                slug=data["slug"],
                defaults={
                    "name": data["name"],
                    "category": category,
                    "brand": brand,
                    "sku": f"ABP-{category.icon.upper()[:3]}-{index:03d}",
                    "short_description": data["short"],
                    "description": description,
                    "price": data["price"],
                    "old_price": data.get("old_price"),
                    "stock": data["stock"],
                    "warranty": data["warranty"],
                    "application": data["application"],
                    "compatible_with": data["compatible"],
                    "specs": specs,
                    "is_active": True,
                    "is_featured": data.get("featured", False),
                },
            )
            created += int(is_created)
            updated += int(not is_created)

        self.stdout.write(
            self.style.SUCCESS(
                f"داده‌ها آماده شد: {len(categories)} دسته‌بندی، {len(brands)} برند، "
                f"{created} محصول جدید، {updated} محصول بروزرسانی‌شده."
            )
        )
